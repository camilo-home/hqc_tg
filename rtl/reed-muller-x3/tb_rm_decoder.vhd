                            report "OK: fase 1 (sin errores) y fase 2 (con errores inyectados) recuperan los 46 simbolos y m del KAT0." severity note;
                        else
                            report "FALLO: " & integer'image(errors) & " errores." severity error;
                        end if;
                        sim_done <= true;
                    end if;
                end if;

                if cyc > TIMEOUT_CYCLES then
                    report "TIMEOUT: recibidos " & integer'image(k) & " de " & integer'image(2 * NUM_SYM) & " simbolos." severity error;
                    sim_done <= true;
                end if;
            end if;
        end if;
    end process;

end behavioral;
