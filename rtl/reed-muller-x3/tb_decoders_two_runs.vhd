    port map (clock => clk, reset_n => reset_n_rm, in_valid => rm_in_valid, in_ready => rm_in_ready,
              data_in => rm_data_in, out_valid => rm_out_valid, out_ready => '1', data_out => rm_data_out);

  u_rs : entity work.rs_decoder
    generic map (N => 46, K => 16, OUTPUT_PARITY_SYMBOLS => RS_PARITY_OUT, FCR => 1, PRIMITIVE_POLYNOMIAL => 285)
    port map (clk => clk, rst => rst, i_end_codeword => rs_i_end, i_start_codeword => rs_i_start,
              i_valid => rs_i_valid, i_consume => rs_i_consume, i_symbol => rs_i_symbol,
              o_in_ready => rs_o_in_ready, o_end_codeword => rs_o_end, o_start_codeword => rs_o_start,
              o_valid => rs_o_valid, o_error => rs_o_error, o_symbol => rs_o_symbol);

  rs_i_consume <= '1';

  -- ===== monitores =====
  monitors : process(clk)
    variable idx : integer range 0 to 47;
  begin
    if rising_edge(clk) then
      if mon_clear = '1' then
        rm_count <= 0; rs_count <= 0; rs_done <= '0'; rs_error_seen <= '0';
      else
        if rm_out_valid = '1' and rm_count <= 45 then
          rm_received(rm_count) <= rm_data_out;
          rm_count <= rm_count + 1;
        end if;
        if rs_o_valid = '1' then
          if rs_o_start = '1' then idx := 0; else idx := rs_count; end if;
          if idx < 16 then rs_received(idx) <= rs_o_symbol; end if;
          if idx < 47 then rs_count <= idx + 1; end if;
          if rs_o_end = '1' then rs_done <= '1'; end if;
        end if;
        if rs_o_error = '1' then rs_error_seen <= '1'; end if;
      end if;
    end if;
  end process;

