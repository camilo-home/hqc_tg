    for run in 0 to NRUNS - 1 loop
      if RESET_BETWEEN_RUNS and run > 0 then do_reset; end if;
      mon_clear <= '1'; tick(2); mon_clear <= '0';

      -- etapa 1: rm_decoder
      feed_rm(run);
