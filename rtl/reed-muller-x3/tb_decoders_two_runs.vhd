    variable first_rm_diff : integer;
    variable stream : sym_arr;
    variable rm_ok  : boolean;

    procedure tick(n : integer) is
    begin
      for q in 1 to n loop
        wait until rising_edge(clk);
      end loop;
    end procedure;

    procedure do_reset is
    begin
      rst <= '1'; reset_n_rm <= '0'; tick(5);
      rst <= '0'; reset_n_rm <= '1'; tick(5);
    end procedure;

    -- 46 bloques al rm_decoder, descendente, con huecos
    procedure feed_rm(run : integer) is
    begin
      for b in 0 to 45 loop
        rm_data_in  <= BLOCKS(run)(b);
        rm_in_valid <= '1';
        tick(1);
        while rm_in_ready /= '1' loop tick(1); end loop;
        rm_in_valid <= '0';
        tick(IDLE_BETWEEN_BLOCKS);
      end loop;
    end procedure;

