            if first_rm_diff < 0 then first_rm_diff := k; end if;
          end if;
        end loop;
      end if;
      rm_ok := (rm_diffs = 0);

      -- etapa 2: rs_decoder con lo que entrego el RM (como en decaps)
      stream := rm_received;
      run_rs(stream, run, rs_diffs);

      if rm_ok and rs_diffs = 0 then
        report "run " & integer'image(run) & ": RM OK, RS OK" severity note;
      else
        run_errors := 1;
        total_errors := total_errors + 1;
        report "run " & integer'image(run) & ": RM " & boolean'image(rm_ok) & " (" & integer'image(rm_diffs) &
               " simbolos distintos, el primero en el " & integer'image(first_rm_diff) & ")  RS: " &
               integer'image(rs_diffs) & " de 16 simbolos de m' distintos" severity error;
        if not rm_ok then      -- el RS solo, con los simbolos que debia haber recibido
          tick(50);
          run_rs(EXP_SYMBOLS(run), run, rs_diffs);
          report "run " & integer'image(run) & ": RS aislado (entrada correcta): " & integer'image(rs_diffs) &
                 " de 16 simbolos de m' distintos" severity note;
        end if;
      end if;
      tick(100);
    end loop;

    if total_errors = 0 then
      report "tb_decoders_two_runs: TODAS LAS EJECUCIONES OK" severity note;
    else
      report "tb_decoders_two_runs: " & integer'image(total_errors) & " ejecucion(es) con error" severity error;
    end if;
    finished <= true;
    wait;
  end process;

end architecture;
