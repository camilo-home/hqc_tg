      variable t : integer;
    begin
      mon_clear <= '1'; tick(2); mon_clear <= '0';
      if not RS_START_OVERLAP then
        rs_i_start <= '1'; tick(1); rs_i_start <= '0';
      end if;
      for k in 0 to 45 loop
        rs_i_symbol <= syms(k);
        rs_i_valid  <= '1';
        if RS_START_OVERLAP and k = 0 then rs_i_start <= '1'; else rs_i_start <= '0'; end if;
        if k = 45 then rs_i_end <= '1'; else rs_i_end <= '0'; end if;
        tick(1);
      end loop;
      rs_i_valid <= '0'; rs_i_start <= '0'; rs_i_end <= '0';
      t := 0;
      while rs_done /= '1' and t < 3000 loop tick(1); t := t + 1; end loop;
      diffs := 0;
      if rs_done /= '1' then
        diffs := 99;
        report "  RS: no llego o_end_codeword (esperando " & integer'image(t) & " ciclos)" severity error;
      else
        for k in 0 to 15 loop
          if rs_received(k) /= EXP_M(run)(k) then diffs := diffs + 1; end if;
        end loop;
      end if;
    end procedure;
